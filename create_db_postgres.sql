-- Enhanced Kinklist :: Postgres schema (legacy app, post-migration)
--
-- Differences from create_db_mysql.sql, all deliberate:
--   * users is merged into answers as the `submitter` JSONB column.
--   * `user` (a Postgres reserved word) becomes `user_uuid`.
--   * hits and stats are dropped; the stats compiler is retired.
--   * No IP address is stored anywhere.
--   * JSON columns become JSONB.

CREATE TABLE IF NOT EXISTS choices (
    id   INTEGER     NOT NULL PRIMARY KEY,
    name VARCHAR(60) NOT NULL
);

